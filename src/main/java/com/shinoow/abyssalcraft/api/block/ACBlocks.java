	private static final RegistryObject<Block>[] CRYSTAL_CLUSTERS = makeClusters();

	/** Crystal Cluster by upstream crystal metadata index (see ACItems.CRYSTAL_NAMES) */
	public static RegistryObject<Block> crystalCluster(int meta) { return CRYSTAL_CLUSTERS[meta]; }

	@SuppressWarnings("unchecked")
	private static RegistryObject<Block>[] makeClusters() {
		RegistryObject<Block>[] array = new RegistryObject[com.shinoow.abyssalcraft.api.item.ACItems.CRYSTAL_NAMES.length];
		for(int i = 0; i < array.length; i++)
			array[i] = get(com.shinoow.abyssalcraft.api.item.ACItems.CRYSTAL_NAMES[i] + "_crystal_cluster");
		return array;
	}

	private static RegistryObject<Block> get(String name) {
		return RegistryObject.create(new ResourceLocation("abyssalcraft", name), ForgeRegistries.BLOCKS);
	}
