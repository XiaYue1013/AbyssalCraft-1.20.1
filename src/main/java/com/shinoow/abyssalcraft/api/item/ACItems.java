	/** Crystal ids in upstream metadata order (see {@link com.shinoow.abyssalcraft.api.item.ICrystal}). */
	public static final String[] CRYSTAL_NAMES = {"iron", "gold", "sulfur", "carbon", "oxygen", "hydrogen", "nitrogen", "phosphorus",
			"potassium", "nitrate", "methane", "redstone", "abyssalnite", "coralium", "dreadium", "blaze", "tin", "copper",
			"silicon", "magnesium", "aluminium", "silica", "alumina", "magnesia", "zinc", "calcium", "beryllium", "beryl"};

	private static final RegistryObject<Item>[] CRYSTALS = makeCrystals("_crystal");
	private static final RegistryObject<Item>[] CRYSTAL_SHARDS = makeCrystals("_crystal_shard");
	private static final RegistryObject<Item>[] CRYSTAL_FRAGMENTS = makeCrystals("_crystal_fragment");

	/** Crystal by upstream metadata index */
	public static RegistryObject<Item> crystal(int meta) { return CRYSTALS[meta]; }
	/** Crystal Shard by upstream metadata index */
	public static RegistryObject<Item> crystalShard(int meta) { return CRYSTAL_SHARDS[meta]; }
	/** Crystal Fragment by upstream metadata index */
	public static RegistryObject<Item> crystalFragment(int meta) { return CRYSTAL_FRAGMENTS[meta]; }

	@SuppressWarnings("unchecked")
	private static RegistryObject<Item>[] makeCrystals(String suffix) {
		RegistryObject<Item>[] array = new RegistryObject[CRYSTAL_NAMES.length];
		for(int i = 0; i < array.length; i++)
			array[i] = get(CRYSTAL_NAMES[i] + suffix);
		return array;
	}

	private static RegistryObject<Item> get(String name) {
		return RegistryObject.create(new ResourceLocation("abyssalcraft", name), ForgeRegistries.ITEMS);
	}
