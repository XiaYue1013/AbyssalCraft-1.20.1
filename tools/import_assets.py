copied_models = {}


def convert_model(kind, upstream_name, new_name=None):
    """Converts upstream models/<kind>/<upstream_name>.json, returns the new model reference"""
    new_name = new_name or upstream_name
    key = (kind, new_name)
    if key in copied_models:
        return copied_models[key]
    src = os.path.join(SRC_ASSETS, 'models', kind, upstream_name + '.json')
    ref = 'abyssalcraft:%s/%s' % (kind, new_name)
    copied_models[key] = ref
    if not os.path.exists(src):
        obj = os.path.join(SRC_ASSETS, 'models', kind, upstream_name + '.obj')
        if os.path.exists(obj):
            return convert_obj(kind, upstream_name, new_name, ref)
        print('  missing upstream model', kind, upstream_name)
        return ref
    gen = os.path.join(GEN, 'models', kind, new_name + '.json')
    if os.path.exists(gen):
        return ref  # generated by datagen, don't shadow it
    m = load_json(src)
    if 'textures' in m:
        m['textures'] = {k: fix_tex(v) for k, v in m['textures'].items()}
    if 'parent' in m:
        m['parent'] = fix_parent(m['parent'])
    for o in m.get('overrides', []):
        if 'model' in o:
            o['model'] = fix_model_ref(o['model'], 'item')
        if 'predicate' in o:
            o['predicate'] = {fix_predicate(k): v for k, v in o['predicate'].items()}
    # These legacy bark overlays contain alpha. Without an explicit cutout
    # layer 1.20 renders the transparent overlay as a solid surface.
    if kind == 'block' and upstream_name in ('dltlog_2', 'dltlog_bark_2'):
        m['render_type'] = 'minecraft:cutout'
    write_json(os.path.join(OUT, 'models', kind, new_name + '.json'), m)
    return ref


def convert_obj(kind, upstream_name, new_name, ref):
    """1.12 Forge OBJ model -> forge:obj loader model (the .obj/.mtl are copied, texture paths in the .mtl updated)"""
    src_dir = os.path.join(SRC_ASSETS, 'models', kind)
    dest_dir = os.path.join(OUT, 'models', kind)
    os.makedirs(dest_dir, exist_ok=True)
    obj = open(os.path.join(src_dir, upstream_name + '.obj'), encoding='utf-8', errors='replace').read()
    particle = None
    mtl_name = re.search(r'(?m)^mtllib\s+(\S+)', obj)
    if mtl_name and os.path.exists(os.path.join(src_dir, mtl_name.group(1))):
        lines = []
        for line in open(os.path.join(src_dir, mtl_name.group(1)), encoding='utf-8', errors='replace').read().splitlines():
            m = re.match(r'^(\s*map_Kd\s+)(\S+)', line)
            if m:
                tex = fix_tex(m.group(2))
                particle = particle or tex
                line = m.group(1) + tex
            lines.append(line)
        with open(os.path.join(dest_dir, mtl_name.group(1)), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write('\n'.join(lines) + '\n')
    with open(os.path.join(dest_dir, upstream_name + '.obj'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(obj)
    model = {'parent': 'minecraft:block/block', 'loader': 'forge:obj',
             'model': 'abyssalcraft:models/%s/%s.obj' % (kind, upstream_name), 'flip_v': True, 'render_type': 'minecraft:cutout'}
    if particle:
        model['textures'] = {'particle': particle}
    display = obj_display(upstream_name) if kind == 'item' else None
    if display:
        model['display'] = display
    write_json(os.path.join(dest_dir, new_name + '.json'), model)
    return ref


def obj_display(upstream_name):
    """1.12 Forge blockstate "inventory" transforms -> model display transforms.

    Forge 1.12 read them as block-centered TRSR transforms with the translation in blocks and the rotations
    multiplied in list order, the same as vanilla display transforms (translation in pixels, XYZ euler angles)."""
    bs = os.path.join(SRC_ASSETS, 'blockstates', upstream_name + '.json')
    if not os.path.exists(bs):
        return None
    try:
        inventory = load_json(bs).get('variants', {}).get('inventory')
    except ValueError:
        print('  unreadable blockstate', bs)
        return None
    transform = (inventory[0] if isinstance(inventory, list) else inventory or {}).get('transform')
    if not isinstance(transform, dict):
        return None
    display = {}
    for view, t in transform.items():
        rotation = [0.0, 0.0, 0.0]
        for r in t.get('rotation', []):
            for axis, angle in r.items():
                rotation['xyz'.index(axis)] += angle
        scale = t.get('scale', 1)
        display[view] = {'rotation': rotation,
                         'translation': [round(v * 16, 4) for v in t.get('translation', [0, 0, 0])],
                         'scale': scale if isinstance(scale, list) else [scale] * 3}
    return display


