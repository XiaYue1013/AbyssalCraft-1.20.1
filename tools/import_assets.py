def fix_parent(parent):
    ns, path = parent.split(':', 1) if ':' in parent else ('minecraft', parent)
    if ns == 'minecraft':
        if '/' not in path:
            path = 'block/' + path
        return 'minecraft:' + path
    kind, name = path.split('/', 1) if '/' in path else ('block', path)
    return convert_model(kind, name)


def fix_model_ref(ref, default_kind):
    ns, path = ref.split(':', 1) if ':' in ref else ('minecraft', ref)
    if ns != 'abyssalcraft':
        return ref
    kind, name = path.split('/', 1) if '/' in path else (default_kind, path)
    return convert_model(kind, name)


def copy_textures():
    src_root = os.path.join(SRC_ASSETS, 'textures')
    n = 0
    for dirpath, _, files in os.walk(src_root):
        rel = os.path.relpath(dirpath, src_root)
        parts = rel.split(os.sep)
        if parts[0] in TEXTURE_DIRS:
            parts[0] = TEXTURE_DIRS[parts[0]]
        dest = os.path.join(OUT, 'textures', *[p for p in parts if p != '.'])
        os.makedirs(dest, exist_ok=True)
        for f in files:
            if f.endswith(('.png', '.mcmeta')):
                # 1.20 resource paths can't have apostrophes (j'zahar.png -> jzahar.png)
                shutil.copy2(os.path.join(dirpath, f), os.path.join(dest, f.replace("'", '')))
                n += 1
    print('textures:', n)


def copy_sounds():
    src = os.path.join(SRC_ASSETS, 'sounds')
    if os.path.isdir(src):
        shutil.copytree(src, os.path.join(OUT, 'sounds'), dirs_exist_ok=True)
    sj = os.path.join(SRC_ASSETS, 'sounds.json')
    if os.path.exists(sj):
        write_json(os.path.join(OUT, 'sounds.json'), load_json(sj))
    print('sounds copied')


MESH_OVERRIDES = {
    'staff_of_the_gatekeeper': [({'abyssalcraft:mode': 1}, 'staff2')],  # rending mode
}


def import_models():
    mp = os.path.join(ROOT, 'tools', 'generated', 'item_model_map.json')
    if not os.path.exists(mp):
        print('tools/generated/item_model_map.json missing, run ./gradlew runData first')
        return
    mapping = json.load(open(mp, encoding='utf-8'))
    for new, old in mapping.items():
        convert_model('item', old, new)
    # 1.12.2 custom mesh definitions (model picked from NBT in code) -> overrides
    for item, overrides in MESH_OVERRIDES.items():
        path = os.path.join(OUT, 'models', 'item', item + '.json')
        if os.path.exists(path):
            m = load_json(path)
            m['overrides'] = [{'predicate': pred, 'model': convert_model('item', model)} for pred, model in overrides]
            write_json(path, m)
    # custom block models referenced (unchecked) by generated blockstates
    bs_dir = os.path.join(GEN, 'blockstates')
    for f in os.listdir(bs_dir) if os.path.isdir(bs_dir) else []:
        data = json.load(open(os.path.join(bs_dir, f), encoding='utf-8'))
        for v in iter_variant_models(data):
            ns, path = v.split(':', 1)
            if ns == 'abyssalcraft' and path.startswith('block/'):
                name = path[len('block/'):]
                if not os.path.exists(os.path.join(GEN, 'models', 'block', name + '.json')):
                    convert_model('block', name)
    print('models converted:', len(copied_models))


def iter_variant_models(data):
    for v in data.get('variants', {}).values():
        for e in (v if isinstance(v, list) else [v]):
            if 'model' in e:
                yield e['model']
    for part in data.get('multipart', []):
        a = part.get('apply', {})
        for e in (a if isinstance(a, list) else [a]):
            if 'model' in e:
                yield e['model']


