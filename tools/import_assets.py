UPSTREAM = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', '_upstream', 'AbyssalCraft'))
SRC_ASSETS = os.path.join(UPSTREAM, 'src', 'main', 'resources', 'assets', 'abyssalcraft')
SRC_JAVA = os.path.join(UPSTREAM, 'src', 'main', 'java', 'com', 'shinoow', 'abyssalcraft')
OUT = os.path.join(ROOT, 'src', 'restricted', 'resources', 'assets', 'abyssalcraft')
GEN = os.path.join(ROOT, 'src', 'generated', 'resources', 'assets', 'abyssalcraft')

TEXTURE_DIRS = {'blocks': 'block', 'items': 'item', 'particles': 'particle'}


def load_json(path):
    s = open(path, encoding='utf-8', errors='replace').read()
    s = re.sub(r'(?m)^\s*//[^\n]*', '', s)
    s = re.sub(r',\s*([}\]])', r'\1', s)
    return json.loads(s, strict=False)


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def fix_tex(ref):
    """1.12 texture reference -> 1.20 texture reference"""
    if not isinstance(ref, str) or ref.startswith('#'):
        return ref
    ns, path = ref.split(':', 1) if ':' in ref else ('minecraft', ref)
    parts = path.split('/')
    if parts[0] in TEXTURE_DIRS:
        parts[0] = TEXTURE_DIRS[parts[0]]
    path = '/'.join(parts)
    if ns == 'minecraft':
        path = VANILLA_TEXTURE_RENAMES.get(path, path)
    return ns + ':' + path


