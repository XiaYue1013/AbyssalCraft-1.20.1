def upstream_translation_keys():
    """Upstream ACItems/ACBlocks field -> translation key, parsed from the 1.12.2 handlers"""
    keys = {}
    class_keys = {}
    for dirpath, _, files in os.walk(SRC_JAVA):
        for f in files:
            if f.endswith('.java'):
                s = open(os.path.join(dirpath, f), encoding='utf-8', errors='replace').read()
                m = re.search(r'(?:super|setTranslationKey)\(\s*"([a-z_0-9]+)"', s)
                if m:
                    class_keys[f[:-5]] = m.group(1)
    for handler in ('ItemHandler.java', 'BlockHandler.java'):
        s = open(os.path.join(SRC_JAVA, 'init', handler), encoding='utf-8', errors='replace').read()
        for m in re.finditer(r'(?:AC(?:Items|Blocks)\.)?([a-zA-Z_0-9]+) = new ([A-Za-z]+)\(([^;]*)', s):
            field, cls, rest = m.groups()
            k = re.search(r'setTranslationKey\("([^"]+)"\)', rest)
            if k:
                keys[field] = k.group(1)
                continue
            lit = re.search(r'"([a-z_0-9]+)"', rest.split(')')[0] if 'Condition' in rest else rest)
            if lit:
                keys[field] = lit.group(1)
            elif cls in class_keys:
                keys[field] = class_keys[cls]
    return keys


