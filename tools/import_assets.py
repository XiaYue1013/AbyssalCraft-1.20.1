def convert_lang():
    mp = os.path.join(ROOT, 'tools', 'generated', 'item_model_map.json')
    items = list(json.load(open(mp, encoding='utf-8')).keys()) if os.path.exists(mp) else []
    bs_dir = os.path.join(GEN, 'blockstates')
    blocks = [f[:-5] for f in os.listdir(bs_dir)] if os.path.isdir(bs_dir) else []
    fields = upstream_translation_keys()
    rename = {}
    unmapped = []
    model_map = json.load(open(mp, encoding='utf-8')) if os.path.exists(mp) else {}
    en = {}
    for line in open(os.path.join(SRC_ASSETS, 'lang', 'en_us.lang'), encoding='utf-8', errors='replace'):
        if '=' in line and not line.startswith('#'):
            k, v = line.rstrip('\r\n').split('=', 1)
            en[k] = v
    for kind, ids, prefix in (('item', items, 'item'), ('block', blocks, 'tile')):
        for i in ids:
            new_key = '%s.abyssalcraft.%s' % (kind, i)
            candidates = []
            if '%s:%s' % (kind, i) in LANG_OVERRIDES:
                candidates.append(LANG_OVERRIDES['%s:%s' % (kind, i)] + '.name')
            if i in fields:
                candidates.append('%s.%s.name' % (prefix, fields[i]))
            m = model_map.get(i)
            if m:
                candidates.append('%s.%s.name' % (prefix, m))
                candidates.append('%s.%s.name' % (prefix, m.replace('_', '.', 1)))
                if '_' in m:
                    candidates.append('%s.%s.name' % (prefix, '.'.join(m.rsplit('_', 1))))
                parts = m.split('_')
                if len(parts) == 2:
                    candidates.append('%s.%s.%s.name' % (prefix, parts[1], parts[0]))
                for suffix in ('_range', '_duration', '_power', '_empty'):
                    if m.endswith(suffix):
                        candidates.append('%s.%s.name' % (prefix, m[:-len(suffix)]))
            found = next((c for c in candidates if c in en), None)
            if found:
                rename.setdefault(found, [])
                if not isinstance(rename[found], list):
                    rename[found] = [rename[found]]
                rename[found].append(new_key)
            else:
                unmapped.append(new_key)
    lang_dir = os.path.join(SRC_ASSETS, 'lang')
    for f in os.listdir(lang_dir):
        if not f.endswith('.lang'):
            continue
        out = {}
        for line in open(os.path.join(lang_dir, f), encoding='utf-8', errors='replace'):
            line = line.rstrip('\n').rstrip('\r')
            if not line or line.startswith('#') or '=' not in line:
                continue
            k, v = line.split('=', 1)
            if k in rename:
                for nk in (rename[k] if isinstance(rename[k], list) else [rename[k]]):
                    out[nk] = v
            elif k.startswith('entity.abyssalcraft.') and k.endswith('.name'):
                old_id = k[len('entity.abyssalcraft.'):-5]
                new_id = ENTITY_NAMES.get(old_id, old_id)
                out['entity.abyssalcraft.' + new_id] = v
                if f == 'en_US.lang' or f == 'en_us.lang':
                    out['item.abyssalcraft.%s_spawn_egg' % new_id] = SPAWN_EGG_NAMES.get(new_id, v + ' Spawn Egg')
            else:
                out[k[:-5] if k.endswith('.name') else k] = v
                out[k] = v
        if 'item.ccluster' in out:
            out['item.abyssalcraft.coralium_gem_cluster'] = out['item.ccluster']
        # crystals: "Crystallized X", "Crystallized X Shard" etc. (1.12.2 built these from postfix formats)
        for name in CRYSTAL_NAMES:
            base = out.get('item.crystal.%s' % name.capitalize())
            if base is None:
                continue
            out['item.abyssalcraft.%s_crystal' % name.lower()] = base
            for kind, key in (('_crystal_shard', 'crystalshard.postfix'), ('_crystal_fragment', 'crystalfragment.postfix')):
                if key in out:
                    out['item.abyssalcraft.%s%s' % (name.lower(), kind)] = out[key].replace('%s', base)
            if 'crystalcluster.postfix' in out:
                out['block.abyssalcraft.%s_crystal_cluster' % name.lower()] = out['crystalcluster.postfix'].replace('%s', base)
        # fluids and their buckets (1.12.2 used Forge's universal bucket, named "<fluid> Bucket" in English)
        for old, new in (('liquidcoralium', 'liquid_coralium'), ('liquidantimatter', 'liquid_antimatter')):
            if 'fluid.' + old in out:
                out['fluid_type.abyssalcraft.' + new] = out['fluid.' + old]
                if f.lower() == 'en_us.lang':
                    out['item.abyssalcraft.%s_bucket' % new] = out['fluid.' + old] + ' Bucket'
        # effects and potions (1.20.1 builds "item.minecraft.<container>.effect.<potion base name>")
        for old, new in (('Cplague', 'coralium_plague'), ('Dplague', 'dread_plague'), ('Antimatter', 'antimatter')):
            if 'potion.' + old in out:
                out['effect.abyssalcraft.' + new] = out['potion.' + old]
            for container in ('potion', 'splash_potion', 'lingering_potion', 'tipped_arrow'):
                if '%s.effect.%s' % (container, old) in out:
                    out['item.minecraft.%s.effect.%s' % (container, new)] = out['%s.effect.%s' % (container, old)]
        # strings added by the port (written for the port, not part of the upstream assets)
        port_lang = os.path.join(ROOT, 'tools', 'port_lang', f[:-5].lower() + '.json')
        if os.path.exists(port_lang):
            out.update(json.load(open(port_lang, encoding='utf-8')))
        write_json(os.path.join(OUT, 'lang', f[:-5].lower() + '.json'), out)
    print('lang converted; unmapped ids:', len(unmapped))
    with open(os.path.join(ROOT, 'tools', 'generated', 'lang_unmapped.txt'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(unmapped))


