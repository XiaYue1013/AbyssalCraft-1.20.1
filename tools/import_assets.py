"""Imports the upstream AbyssalCraft 1.12.2 assets into src/restricted/resources for LOCAL development builds.

The upstream textures, models and sounds are All Rights Reserved (see README.md). This script only converts
them on the developer's machine; src/restricted/ is git-ignored and must never be published.

usage: python tools/import_assets.py [path/to/upstream/AbyssalCraft]   (default: ../_upstream/AbyssalCraft)

What it does:
  * textures/blocks -> textures/block, textures/items -> textures/item, other texture folders copied as-is
  * sounds + sounds.json
  * item models listed in tools/generated/item_model_map.json (written by ./gradlew runData) are converted
    to the new item ids, together with the block/item models they reference
  * custom block models referenced by the generated blockstates are converted
  * lang/*.lang -> lang/*.json, with item/block/entity keys renamed to the new registry ids
  * structure templates (tools/import_structures.py)
"""
